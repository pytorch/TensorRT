"""The KernelGenerator settings of the workloads' generated kernels.

Workloads in this directory offer knob values (``kernels.decode_blocks=
"generated"``, ``kernels.generated``, ``kernels.gdn_scan="generated"``) whose
regions run kernels that PR 4914's ``torch_tensorrt.region.KernelGenerator``
writes: an LLM author proposes Triton kernels during compilation, the
generator checks each one against the region's PyTorch code, times it
against TensorRT's own build of the region, and caches the kernel it
accepts. :func:`make_generator` is the one generator configuration they all
use, so every build of a region asks for the same kernel.

The kernel cache key includes the compilation's engine options (such as
``optimization_level``, ``use_fp32_acc``, ``disable_tf32`` and
``build_route``), the generator's validation settings and the text of its
instruction files. A cached kernel is therefore reused only by a build with
the same options, so kernels are generated by the workload's own build (a
session prepares each generated value once, before its search), never by a
separate script with other options. A workload's notes file is part of the
key too: editing one starts a new cache for its regions.

The cache directory is a workload's ``kernel_cache`` argument, else
``$TORCHTRT_KERNEL_CACHE``, else :data:`DEFAULT_KERNEL_CACHE`
(:func:`kernel_cache`).
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Mapping, Sequence

# Where generated kernels are cached unless a workload's kernel_cache argument
# says otherwise: this environment variable, else this directory.
KERNEL_CACHE_ENV = "TORCHTRT_KERNEL_CACHE"
DEFAULT_KERNEL_CACHE = "/dev/shm/exp/kcache"
# Seconds the generator may spend on one region: authoring, checking and
# timing candidates. It is not part of the cache key.
TIMEOUT_S = 1800.0
# What a generated value requires of a config: TensorRT 11.4 reloads plugin
# modules on every enqueue outside CUDA graphs.
PLUGIN_REQUIRES: dict[str, Any] = {"runtime.cudagraphs": True}
# The start of every kernels.generated knob's description: what the generator
# does with a region.
GENERATED_INTRO = (
    "Regions whose kernel PR 4914's KernelGenerator writes during the build: an "
    "LLM author (Claude) proposes Triton kernels for the region, and the "
    "generator keeps one only if it computes what the region's PyTorch code "
    "computes and runs at least as fast as TensorRT's own build of the region; "
    "the kernel then runs inside the TensorRT engine as a fused_kernel plugin."
)
# How every generated value's kernels are cached, prepared and pinned.
CACHE_NOTE = (
    "Kernels are cached in the workload's kernel_cache directory, keyed by the "
    "region and the engine options (precision, build route and accumulation "
    "included): a build whose options have no cached kernel generates it (up to "
    f"{TIMEOUT_S / 60:.0f} minutes per distinct region). A session prepares the "
    "value once, before its search, holds later runs to the kernels it prepared "
    "and refuses a config whose options would need a kernel it did not prepare."
)
# Notes files named without a directory live next to this module.
_HERE = Path(__file__).resolve().parent


def kernel_cache(directory: str | None = None) -> str:
    """The kernel cache directory: ``directory``, else the environment's, else the default."""
    return directory or os.environ.get(KERNEL_CACHE_ENV) or DEFAULT_KERNEL_CACHE


def notes_path(notes: str | Path) -> Path:
    """An instruction file: a bare file name is taken from this directory."""
    path = Path(notes)
    if not path.is_absolute() and path.parent == Path("."):
        path = _HERE / path
    return path


def make_generator(
    cache_dir: str | Path,
    notes: str | Path | None = None,
    *,
    timeout_s: float = TIMEOUT_S,
    fp32_matmul_precision: str = "highest",
) -> Any:
    """The ``KernelGenerator`` every generated region of these workloads uses.

    Claude writes Triton kernels (``provider="claude"``, ``backend="triton"``,
    the CLI's default model); a kernel is
    accepted only if it is at least as fast as TensorRT's own build of the
    region (``objective="tensorrt"``, ``min_speedup=1.0``). Plugin pointers
    are taken as 16-byte aligned, as TensorRT allocates them
    (``aligned_io``), and the author may ask for compiler and execution
    diagnostics (``diagnostics``). ``notes`` is the workload's notes file of
    measured facts about its regions (a bare file name is looked up in this
    directory), or ``None``. ``fp32_matmul_precision`` is the generator's: how
    exact the region's float32 matrix products must be (``"high"`` also
    accepts the error they have with TF32). Accepted kernels are cached in
    ``cache_dir``.

    A workload passes the same arguments to every build, so that the build
    that generates a region's kernel and every later build agree on the
    cache key.
    """
    from torch_tensorrt.region import KernelGenerator

    return KernelGenerator(
        provider="claude",
        backend="triton",
        instruction_files=() if notes is None else (str(notes_path(notes)),),
        timeout_s=float(timeout_s),
        cache_dir=str(cache_dir),
        objective="tensorrt",
        min_speedup=1.0,
        fp32_matmul_precision=fp32_matmul_precision,
        aligned_io=True,
        diagnostics=True,
    )


def describe(generator: Any) -> dict[str, Any]:
    """What a build reports about the generator its regions used."""
    return {
        "kernel_cache": str(generator.cache_dir),
        "generator_notes": [Path(path).name for path in generator.instruction_files],
        "generator_fp32_matmul_precision": generator.fp32_matmul_precision,
    }


def check_generated(
    values: Mapping[str, Any], choices: Sequence[str], *, conflict: str = ""
) -> str:
    """Check a config's ``kernels.generated``; return its value (``"none"`` when unset).

    A generated value needs :data:`PLUGIN_REQUIRES` and
    ``kernels.inductor="none"``: the knob's ``requires``, checked here too for
    builds that do not go through the Auto-Tuner's resolution. ``conflict``
    says why ``kernels.inductor`` must be ``"none"``.
    """
    generated = values.get("kernels.generated", "none")
    if generated not in choices:
        raise ValueError(
            f"Unknown kernels.generated {generated!r}: must be one of {tuple(choices)}"
        )
    if generated == "none":
        return generated
    if not values.get("runtime.cudagraphs"):
        raise ValueError(
            f"kernels.generated={generated!r} needs runtime.cudagraphs=True: "
            "TensorRT 11.4 reloads plugin modules on every enqueue outside CUDA "
            "graphs"
        )
    if values.get("kernels.inductor", "none") != "none":
        reason = f": {conflict}" if conflict else ""
        raise ValueError(
            f"kernels.generated={generated!r} needs kernels.inductor='none'{reason}"
        )
    return generated
